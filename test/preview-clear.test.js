import { test } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import sharp from "sharp";
import { chromium } from "playwright-core";
import { createApp } from "../src/server.js";

test("PREVIEW CLEAR：UI準備・実画素FADE・音声減衰・即時CLEAR・再接続", { skip: !process.env.CHROMIUM_PATH }, async (t) => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "playout-preview-clear-"));
  const runtime = createApp({ dir, password: "test" });
  await new Promise(r => runtime.server.listen(0, "127.0.0.1", r));
  const base = `http://127.0.0.1:${runtime.server.address().port}`;
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH, args: ["--no-sandbox", "--autoplay-policy=no-user-gesture-required"] });
  t.after(async () => {
    await browser.close();
    for (const ws of runtime.wss.clients) ws.terminate();
    await new Promise(r => runtime.server.close(r));
    fs.rmSync(dir, { recursive: true, force: true });
  });
  const context = await browser.newContext({ httpCredentials: { username: "admin", password: "test" }, viewport: { width: 1280, height: 720 } });
  const admin = await context.newPage();
  const out = await browser.newPage({ viewport: { width: 320, height: 180 } });
  await admin.goto(base);
  await out.goto(base + "/receiver?transparent=1");
  const png = await sharp({ create: { width: 32, height: 18, channels: 4, background: "red" } }).png().toBuffer();
  await admin.locator("#upload").setInputFiles({ name: "red.png", mimeType: "image/png", buffer: png });
  await admin.waitForFunction(() => document.querySelectorAll(".card").length === 1);
  await admin.locator('[data-command="cut"]').click();
  await out.waitForFunction(() => document.querySelector("#output img")?.complete);
  const program = runtime.store.state.program;
  await admin.locator('[data-command="preview-clear"]').click();
  await admin.waitForFunction(() => document.querySelector("#previewName").textContent === "CLEAR（透明）");
  assert.equal(runtime.store.state.program, program);
  assert.equal(await admin.locator("#preview").evaluate(el => getComputedStyle(el).backgroundColor), "rgba(0, 0, 0, 0)");
  await admin.locator("#fadeMs").fill("1200");
  await admin.locator("#saveSettings").click();
  await admin.locator('[data-command="take"]').click();
  await out.waitForFunction(() => document.querySelector("#output img")?.getAnimations().length > 0);
  // Freeze the actual fade at its midpoint and inspect rendered alpha pixels.
  await out.evaluate(() => { for (const el of document.querySelector("#output").children) for (const a of el.getAnimations()) { a.pause(); a.currentTime = 600; } });
  const frame = await out.screenshot({ omitBackground: true });
  const alpha = (await sharp(frame).ensureAlpha().stats()).channels[3];
  assert.ok(alpha.mean > 110 && alpha.mean < 145, `midpoint alpha=${alpha.mean}`);
  await out.evaluate(() => { for (const el of document.querySelector("#output").children) for (const a of el.getAnimations()) a.finish(); });
  await out.waitForFunction(() => !document.querySelector("#output img"));
  const assertClear = async () => assert.equal((await sharp(await out.screenshot({ omitBackground: true })).ensureAlpha().stats()).channels[3].max, 0);
  await assertClear();
  await out.reload();
  await out.waitForFunction(() => getComputedStyle(document.querySelector("#output")).backgroundColor === "rgba(0, 0, 0, 0)");
  await assertClear();
  await admin.reload();
  await admin.waitForFunction(() => document.querySelector("#previewName").textContent === "CLEAR（透明）");
  await admin.locator("#upload").setInputFiles(path.resolve("test/fixtures/sample.mp4"));
  await admin.waitForFunction(() => document.querySelectorAll(".card").length === 2);
  await admin.locator(".card").last().click();
  await admin.locator('[data-command="cut"]').click();
  await out.waitForFunction(() => document.querySelector("#output video")?.currentTime > 0.1);
  await out.evaluate(() => window.oldVideo = document.querySelector("#output video"));
  await admin.locator('[data-command="preview-clear"]').click();
  await admin.locator('[data-command="take"]').click();
  await out.waitForFunction(() => window.oldVideo.volume < 0.8 && window.oldVideo.volume > 0.1);
  assert.equal(await out.evaluate(() => window.oldVideo.paused), false);
  await admin.locator('[data-command="clear"]').click();
  await out.waitForFunction(() => window.oldVideo.paused && !document.querySelector("#output video"));
  await assertClear();
});
